#!/usr/bin/env python3
"""Generate Unity C# DTOs from contracts/messages.schema.json."""

from __future__ import annotations

import json
import re
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "contracts" / "messages.schema.json"
OUTPUT_PATH = ROOT / "unity-ar" / "Assets" / "_Project" / "Scripts" / "Bridge" / "LociMessageModels.Generated.cs"

ENUM_TYPE_OVERRIDES = {
    "topicId": "LociTopicId",
    "arAvailability": "LociArAvailability",
    "state": "LociSessionState",
    "reason": "LociTrackingReason",
    "code": "LociErrorCode",
}


def pascal_case(value: str) -> str:
    parts = re.findall(r"[A-Za-z0-9]+", value)
    return "".join(part[0].upper() + part[1:] for part in parts)


def csharp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def property_type(prop_name: str, prop_schema: dict, enum_registry: dict) -> str:
    reference = prop_schema.get("$ref")
    if reference:
        ref_name = reference.rsplit("/", 1)[-1]
        if ref_name == "topicId":
            return ENUM_TYPE_OVERRIDES["topicId"]
        if ref_name == "emptyPayload":
            return "EmptyPayload"
        raise ValueError(f"Unsupported schema reference: {reference}")

    if "enum" in prop_schema:
        enum_name = ENUM_TYPE_OVERRIDES.get(prop_name, "Loci" + pascal_case(prop_name))
        enum_registry[enum_name] = list(prop_schema["enum"])
        return enum_name

    schema_type = prop_schema.get("type")
    type_names = {"string": "string", "number": "double", "integer": "int", "boolean": "bool"}
    if schema_type not in type_names:
        raise ValueError(f"Unsupported schema type for {prop_name}: {schema_type}")
    return type_names[schema_type]


def payload_schema_for(message_schema: dict, defs: dict) -> dict:
    payload_schema = message_schema.get("properties", {}).get("payload")
    if payload_schema is None:
        raise ValueError("Message schema is missing a payload property")
    if "$ref" in payload_schema:
        ref_name = payload_schema["$ref"].rsplit("/", 1)[-1]
        return defs[ref_name]
    return payload_schema


def payload_class_name(message_type: str) -> str:
    return pascal_case(message_type) + "Payload"


def generate(schema: dict) -> str:
    defs = schema["$defs"]
    message_refs = schema["oneOf"]
    messages = []
    enum_registry = {"LociTopicId": list(defs["topicId"]["enum"])}

    for reference in message_refs:
        ref_name = reference["$ref"].rsplit("/", 1)[-1]
        message_schema = defs[ref_name]
        message_type = message_schema["properties"]["type"]["const"]
        payload_schema = payload_schema_for(message_schema, defs)
        messages.append((message_type, message_schema, payload_schema))
        properties = payload_schema.get("properties", {})
        for name, prop_schema in properties.items():
            property_type(name, prop_schema, enum_registry)

    lines = [
        "// <auto-generated />",
        "// Generated by scripts/generate_unity_message_models.py from contracts/messages.schema.json.",
        "using System;",
        "using System.Runtime.Serialization;",
        "using Newtonsoft.Json;",
        "using Newtonsoft.Json.Linq;",
        "using Newtonsoft.Json.Converters;",
        "",
        "namespace Loci.Bridge",
        "{",
        "    public static class LociMessageTypes",
        "    {",
    ]

    for message_type, _, _ in messages:
        member_name = pascal_case(message_type)
        lines.append(f"        public const string {member_name} = {csharp_string(message_type)};")

    lines.extend(["    }", "", "    [JsonObject(MemberSerialization.OptIn)]", "    public sealed class LociMessageEnvelope", "    {"])
    envelope_properties = [
        ("v", "int", True),
        ("id", "string", True),
        ("type", "string", True),
        ("payload", "JToken", True),
        ("replyTo", "string", False),
    ]
    for json_name, cs_type, required in envelope_properties:
        requirement = ", Required = Required.Always" if required else ""
        lines.append(f"        [JsonProperty({csharp_string(json_name)}{requirement})]")
        lines.append(f"        public {cs_type} {pascal_case(json_name)} {{ get; set; }}")
        lines.append("")
    lines.extend([
        "        public bool IsValid(out string error)",
        "        {",
        "            if (V != 1) { error = \"Envelope version must be 1.\"; return false; }",
        "            if (string.IsNullOrEmpty(Id)) { error = \"Envelope id must be a non-empty string.\"; return false; }",
        "            if (string.IsNullOrEmpty(Type)) { error = \"Envelope type must be a non-empty string.\"; return false; }",
        "            if (Payload == null || Payload.Type != JTokenType.Object) { error = \"Envelope payload must be an object.\"; return false; }",
        "            if (ReplyTo != null && ReplyTo.Length < 1) { error = \"Envelope replyTo must be non-empty when present.\"; return false; }",
        "            error = null;",
        "            return true;",
        "        }",
        "    }",
        "",
    ])

    for enum_name, values in enum_registry.items():
        lines.extend([
            "    [JsonConverter(typeof(StringEnumConverter))]",
            f"    public enum {enum_name}",
            "    {",
        ])
        for value in values:
            member_name = pascal_case(value)
            if value.startswith("E-"):
                member_name = "E" + value[2:]
            lines.append(f"        [EnumMember(Value = {csharp_string(value)})]")
            lines.append(f"        {member_name},")
        lines.extend(["    }", ""])

    for message_type, _, payload_schema in messages:
        class_name = payload_class_name(message_type)
        properties = payload_schema.get("properties", {})
        required_names = set(payload_schema.get("required", []))
        lines.extend([
            "    [JsonObject(MemberSerialization.OptIn)]",
            f"    public sealed class {class_name}",
            "    {",
        ])
        for name, prop_schema in properties.items():
            cs_type = property_type(name, prop_schema, enum_registry)
            if name not in required_names and cs_type in {"double", "int", "bool"}:
                cs_type += "?"
            elif name not in required_names and cs_type.startswith("Loci"):
                cs_type += "?"
            requirement = ", Required = Required.Always" if name in required_names else ""
            lines.append(f"        [JsonProperty({csharp_string(name)}{requirement})]")
            lines.append(f"        public {cs_type} {pascal_case(name)} {{ get; set; }}")
            lines.append("")

        lines.extend([
            "        public bool IsValid(out string error)",
            "        {",
        ])
        constraints = []
        for name, prop_schema in properties.items():
            cs_name = pascal_case(name)
            min_length = prop_schema.get("minLength")
            if min_length:
                if name in required_names:
                    constraints.append((f"{cs_name} == null || {cs_name}.Length < {min_length}", f"{name} must contain at least {min_length} character(s)."))
                else:
                    constraints.append((f"{cs_name} != null && {cs_name}.Length < {min_length}", f"{name}, when present, must contain at least {min_length} character(s)."))
            exclusive_minimum = prop_schema.get("exclusiveMinimum")
            if exclusive_minimum is not None:
                constraints.append((f"{cs_name} <= {exclusive_minimum}", f"{name} must be greater than {exclusive_minimum}."))
            minimum = prop_schema.get("minimum")
            if minimum is not None:
                constraints.append((f"{cs_name} < {minimum}", f"{name} must be at least {minimum}."))
        for expression, message in constraints:
            lines.append(f"            if ({expression}) {{ error = {csharp_string(message)}; return false; }}")
        lines.extend([
            "            error = null;",
            "            return true;",
            "        }",
            "    }",
            "",
        ])

    lines.extend([
        "    public static class LociMessageModelRegistry",
        "    {",
        "        public static Type PayloadTypeFor(string messageType)",
        "        {",
        "            switch (messageType)",
        "            {",
    ])
    for message_type, _, _ in messages:
        lines.append(f"                case LociMessageTypes.{pascal_case(message_type)}: return typeof({payload_class_name(message_type)});")
    lines.extend([
        "                default: return null;",
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    generated = generate(schema)
    OUTPUT_PATH.write_text(generated, encoding="utf-8", newline="\n")
    guid = uuid.uuid5(uuid.NAMESPACE_URL, "loci-generated:" + OUTPUT_PATH.relative_to(ROOT).as_posix()).hex
    meta_path = OUTPUT_PATH.with_name(OUTPUT_PATH.name + ".meta")
    meta_path.write_text(
        f"fileFormatVersion: 2\nguid: {guid}\nMonoImporter:\n  externalObjects: {{}}\n  serializedVersion: 2\n  defaultReferences: []\n  executionOrder: 0\n  icon: {{instanceID: 0}}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Generated {OUTPUT_PATH.relative_to(ROOT)} from {SCHEMA_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
